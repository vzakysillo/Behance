export const SOCIAL_PLATFORMS = Object.keys(SOCIAL_ICONS);

export const parseSocials = (socials: string[]) =>
  socials
    .filter((s) => s.includes(":"))
    .map((s) => {
      const idx = s.indexOf(":");
      return { platform: s.slice(0, idx), url: s.slice(idx + 1) };
    })
    .filter((s) => SOCIAL_ICONS[s.platform] && s.url);

export const getSocialUrl = (socials: string[], platform: string): string => {
  const entry = socials.find((s) => s.startsWith(`${platform}:`));
  return entry ? entry.slice(platform.length + 1) : "";
};

export const setSocialUrl = (socials: string[], platform: string, url: string): string[] => {
  const filtered = socials.filter((s) => !s.startsWith(`${platform}:`));
  return url ? [...filtered, `${platform}:${url}`] : filtered;
};
